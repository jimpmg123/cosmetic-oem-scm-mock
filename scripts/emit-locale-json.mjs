/**
 * Merges ko + overrides → en/zh JSON, then emits dictionaries.generated.ts for the app bundle.
 * Avoids Turbopack HMR issues with direct JSON imports in translations.ts.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const locales = path.join(root, "src/lib/i18n/locales");
const outTs = path.join(root, "src/lib/i18n/dictionaries.generated.ts");

function loadOptional(name) {
  const p = path.join(locales, name);
  if (!fs.existsSync(p)) return {};
  return JSON.parse(fs.readFileSync(p, "utf8"));
}

const ko = JSON.parse(fs.readFileSync(path.join(locales, "ko.json"), "utf8"));

const en = {
  ...ko,
  ...loadOptional("en-overrides.json"),
  ...loadOptional("en-overrides-b.json"),
  ...loadOptional("en-overrides-c.json"),
  ...loadOptional("en-overrides-d.json"),
  ...loadOptional("en-overrides-e.json"),
};
const zh = {
  ...ko,
  ...loadOptional("zh-overrides.json"),
  ...loadOptional("zh-overrides-b.json"),
  ...loadOptional("zh-overrides-c.json"),
  ...loadOptional("zh-overrides-d.json"),
  ...loadOptional("zh-overrides-e.json"),
};

fs.writeFileSync(path.join(locales, "en.json"), `${JSON.stringify(en, null, 2)}\n`);
fs.writeFileSync(path.join(locales, "zh.json"), `${JSON.stringify(zh, null, 2)}\n`);

const ts = `/** Auto-generated by scripts/emit-locale-json.mjs — do not edit manually */\n\nexport const dictionaries = {\n  ko: ${JSON.stringify(ko)},\n  en: ${JSON.stringify(en)},\n  zh: ${JSON.stringify(zh)},\n} as const satisfies Record<"ko" | "en" | "zh", Record<string, string>>;\n`;

fs.writeFileSync(outTs, ts);
console.log(
  "i18n:",
  Object.keys(ko).length,
  "keys → en.json, zh.json, dictionaries.generated.ts",
);
